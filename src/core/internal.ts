/**
 * Маркер собственного вызова: Symbiont не должен реагировать сам на себя.
 *
 * Найдено догфудингом: свои LLM-проходы плагин делает через headless `claude -p`,
 * а это ПОЛНОЦЕННАЯ сессия Claude Code — у неё срабатывают хуки установленного
 * Symbiont. Дочерний процесс наследует cwd родителя, поэтому проход, запущенный
 * из временного проекта, порождал в корне данных владельца паспорт-призрак
 * (50 каталогов симптомом; настоящий session_id в них и выдал источник).
 * Хуже мусора — рекурсия: плагин анализировал проект внутри собственного вызова,
 * тратя токены на работу, результат которой никто не прочтёт.
 *
 * Механика — переменная окружения, а не флаг CLI: флаги отключения плагинов
 * зависят от версии Claude Code (feature detection вместо version pinning,
 * CONCEPT §7), а свой маркер работает всегда и переживает обновления.
 * Наследование env дочерними процессами гарантирует, что метка не потеряется
 * на любой глубине вложенности.
 */
export const INTERNAL_ENV = 'SYMBIONT_INTERNAL'

/** true — процесс порождён самим Symbiont (его каналы должны молчать). */
export function isInternalCall(env: Record<string, string | undefined> = process.env): boolean {
  return env[INTERNAL_ENV] === '1'
}

/** Окружение для дочернего процесса: помечено как внутреннее. */
export function internalEnv(
  env: Record<string, string | undefined> = process.env,
): Record<string, string | undefined> {
  return { ...env, [INTERNAL_ENV]: '1' }
}
