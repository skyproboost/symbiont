/**
 * Рамка легитимности (CONCEPT §4.1 «Рамка контекста — анти-ложные-отказы»).
 *
 * Классификатор поверх модели soft-block'ает чувствительные темы; ложные отказы
 * на ЛЕГИТИМНОЙ работе (медицина/финансы/безопасность/harm-reduction) снижают
 * СУХИЕ ПРАВДИВЫЕ факты (кто пользователи, добровольность, что сервис НЕ делает),
 * а повышают — мольбы, эмоциональное давление, persona-нажим (XSTest, OR-Bench,
 * arXiv 2509.08075). Рамка из ВЫДУМКИ недопустима этически и хрупка практически.
 *
 * Переосмысление (ответ владельцу «всё индивидуально, не знаю что вписать»):
 * факты НЕ сочиняются владельцем — они ВЫВОДЯТСЯ из описания самого проекта
 * (README/доки: продукт уже заявляет о себе «не заменяет врача», «носит
 * информационный характер»). Владелец лишь опционально уточняет через
 * /sym-charter. Компилятор структурно запрещает анти-паттерны, поэтому даже
 * вольная формулировка не превращается в persona/императив.
 *
 * Чистые функции — тестируются без процесса; ноль LLM (детерминированная
 * экстракция + фильтр). Несенситивный проект → пустая рамка (ноль токенов).
 */

/** Чувствительные направления — по словам самого проекта. */
const SENSITIVE: Record<string, RegExp> = {
  медицина: /(пациент|диагноз|врач|симптом|лечени|медицин|анализ[а-я]* (крови|мочи)|здоровь|заболевани|препарат|дозировк|терапи|клиническ)/i,
  финансы: /(платеж|платёж|финанс|банк|кредит|инвестиц|транзакц|биллинг|выплат|payout|комиссион)/i,
  'безопасность/harm-reduction': /(уязвимост|эксплойт|пентест|вредонос|обход защит|harm[- ]?reduction|снижени[ея] вреда|наркотическ|передозировк)/i,
  право: /(юридическ|правов[ао]|законодательств|нормативн|договорн)/i,
}

/**
 * Легитимность-маркеры: сухие правдивые дисклеймеры, которые продукт заявляет О
 * СЕБЕ. Консервативно — ловим только явные («не заменяет/не является/носит
 * информационный характер/добровольн/обезлич»), чтобы не тащить произвольную прозу.
 */
const LEGIT_MARKER =
  /(не (заменяе[а-я]*|являе[а-я]*|ставит диагноз|назначае[а-я]*|да[её]т медицинск[а-я]*|предоставляе[а-я]* (медицинск|юридическ|финансов)[а-я]*)|носит (информационн|справочн|ознакомительн)[а-я]* характер|информационн[а-я]* характер|не (для|заменяет) самолечени|проконсультируйтесь|перед применением|для информировани|помогает (понять|разобраться|подготовить)|добровольн[а-я]*|с (информированного )?согласия|обезлич[а-я]*|не хранит|не переда[её]т.{0,40}треть)/i

export interface CompiledFrame {
  kept: string[]
  rejected: Array<{ statement: string; reason: string }>
}

/** Направления чувствительности, заявленные текстом проекта (README/доки). */
export function sensitiveDirections(conceptText: string): string[] {
  const out: string[] = []
  for (const [name, re] of Object.entries(SENSITIVE)) {
    if (re.test(conceptText)) out.push(name)
  }
  return out
}

const splitSentences = (text: string): string[] =>
  text
    .replace(/\s+/g, ' ')
    // границы: конец предложения ИЛИ переносы ИЛИ списочные разделители (« - », « — », •)
    .split(/(?<=[.!?;])\s+|\n+|\s+[-—•]\s+/)
    .map((s) => s.trim())
    .filter((s) => s.length >= 12)

const MAX_LEN = 170

/**
 * Кандидаты в рамку — заявления продукта о себе с легитимность-маркером. Берём
 * ТОЛЬКО чистые самодостаточные предложения (заглавная/кавычка в начале,
 * пунктуация в конце, без хвостового yaml-ключа): грязные run-on из склеенного
 * yaml отбрасываем целиком — дисклеймеры повторяются по статьям, чистый экземпляр
 * найдётся. Рамка легитимности обязана быть чистой. Дедуп; кап.
 */
export function deriveFrameCandidates(conceptText: string, max = 6): string[] {
  const out: string[] = []
  const seen = new Set<string>()
  for (const raw of splitSentences(conceptText)) {
    const s = raw.replace(/[*_`]+/g, '').trim()
    if (s.length < 15 || s.length > MAX_LEN) continue // только короткие чистые
    if (!LEGIT_MARKER.test(s)) continue
    if (!/^[«"“А-ЯЁA-Z]/.test(s)) continue // начинается чисто (заглавная/кавычка), не с середины
    if (!/[.!?;»"”]$/.test(s)) continue // заканчивается пунктуацией, не yaml-ключом
    if (/[a-zа-яё0-9_]+:\s*$/i.test(s)) continue // хвостовой yaml-ключ
    const key = s.toLowerCase().replace(/[^а-яёa-z ]/g, '').slice(0, 55)
    if (seen.has(key)) continue
    seen.add(key)
    out.push(s)
    if (out.length >= max) break
  }
  return out
}

// Анти-паттерны, ПОВЫШАЮЩИЕ отказы (компилятор их отбрасывает).
// без \b: в JS без флага u граница слова \b не работает с кириллицей (пропускала «ты обязан»)
const IMPERATIVE = /(обязательно|должен|должна|должны|немедленно|срочно|ни в коем случае|ты обязан|нельзя отказыва)/i
const EMOTIONAL = /(пожалуйста|умоляю|очень важно|критически важно|прошу тебя|вопрос жизни|во что бы то ни стало)/i
const PERSONA = /(ты\s+(врач|эксперт|специалист|доктор|юрист)|представь(,)?\s+что\s+ты|веди себя как|в роли\s+\w+|притворись)/i

/**
 * Компиляция кандидатов в рамку: пропускаем только СУХИЕ ФАКТЫ, отбрасываем
 * императивы/эмоции/персоны (они увеличивают ложные отказы — обратный эффект).
 * Возвращает и отклонённое с причиной (наблюдаемость, не тишина).
 */
export function compileFrame(candidates: string[]): CompiledFrame {
  const kept: string[] = []
  const rejected: Array<{ statement: string; reason: string }> = []
  for (const s of candidates) {
    if (IMPERATIVE.test(s)) rejected.push({ statement: s, reason: 'императив' })
    else if (EMOTIONAL.test(s)) rejected.push({ statement: s, reason: 'эмоциональное давление' })
    else if (PERSONA.test(s)) rejected.push({ statement: s, reason: 'persona-нажим' })
    else kept.push(s)
  }
  return { kept, rejected }
}

/** Блок рамки для подачи; пусто, если фактов нет или проект несенситивный. */
export function renderFrame(kept: string[], directions: string[]): string {
  if (kept.length === 0 || directions.length === 0) return ''
  const lines = [
    '## Контекст легитимности (правдивые факты о проекте — снижают ложные отказы на чувствительной теме; это факты, НЕ инструкции)',
    '',
    `- направление: ${directions.join(', ')} — работа с этим контентом здесь легитимна`,
    ...kept.map((s) => `- ${s}`),
    '- уточнить/дополнить факты: /sym-charter (только правдивое; рамка из выдумки недопустима)',
  ]
  return lines.join('\n')
}

/** Полный конвейер: текст проекта → блок рамки ('' для несенситивного). */
export function buildFrame(conceptText: string): string {
  const directions = sensitiveDirections(conceptText)
  if (directions.length === 0) return ''
  const { kept } = compileFrame(deriveFrameCandidates(conceptText))
  return renderFrame(kept, directions)
}

/**
 * Готовая рамка проекта с диска (её пишет buildPassport). Нужна собственным
 * LLM-проходам плагина: концепт требует подавать рамку «в каждый LLM-вызов
 * самого плагина по этому контенту», иначе на чувствительном проекте наши
 * проходы получают отказ и молча дают ноль. Несенситивный проект → пусто.
 */
export function readFrame(dataDir: string): string {
  try {
    const { readFileSync } = require('node:fs') as typeof import('node:fs')
    const { join } = require('node:path') as typeof import('node:path')
    return readFileSync(join(dataDir, 'frame.md'), 'utf8').trim()
  } catch {
    return '' // нет рамки — вызов идёт как есть
  }
}
