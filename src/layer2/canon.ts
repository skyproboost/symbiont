/**
 * Канонический вид текста для сверки цитаты с файлом. Отдельным модулем: им
 * пользуются и разбор ответа слоя 2, и хранилище улик, которое разбор сам зовёт.
 */

/**
 * Разметка начала строки, которую модель, цитируя, переставляет: отступ,
 * маркер комментария, маркер списка — в любом сочетании («//  • »).
 */
const LINE_MARKUP = /^\s*(?:(?:\/\/+|\/\*+|\*+\/?|#+|<!--|--|;+|[•·▪‣]|-(?=\s))\s*)*/

/**
 * Без разметки начала строк, строки склеены, любая пробельная серия — один
 * пробел. Слова, их регистр и порядок не трогаются.
 */
export function canonText(text: string): string {
  return text
    .split(/\r?\n/)
    .map((l) => l.replace(LINE_MARKUP, ''))
    .join(' ')
    .replace(/\s+/g, ' ')
    .trim()
}
