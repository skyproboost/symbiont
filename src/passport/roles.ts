const GENERIC: Omit<TableRole, 'axis'> = {
  lens: 'что по этой оси может регресснуть от правки',
  checks: ['какие сигналы оси затронуты', 'чем докажем, что не стало хуже'],
  search: 'passport_conventions по области',
}

/** Роли из активных фактов профиля (area «профиль качества»). */
export function rolesFromProfile(profileFacts: Array<Pick<FactRow, 'statement'>>): TableRole[] {
  const roles: TableRole[] = []
  for (const f of profileFacts) {
    const axis = f.statement.split('—')[0].trim()
    const base = ROLE_CATALOG[axis] ?? GENERIC
    roles.push({ axis, ...base })
  }
  return roles
}

/**
 * Сигналы high-stakes задачи (CONCEPT §5: панель/стол — только по триггеру;
 * здесь дешёвый триггер симулированного стола — цена ошибки в самом промпте).
 */
const HIGH_STAKES = /(миграци|схем[ау] (бд|данных)|drop|truncate|delete from|депло[йя]|релиз|в прод|production|секрет|токен|пароль|api-?ключ|оплат|платеж|платёж|биллинг|деньг|безопасн|уязвим|cors|csp|права доступа|удали (весь|все|базу)|rm -rf)/i

export function isHighStakes(prompt: string): boolean {
  return HIGH_STAKES.test(prompt)
}

/** Компактная инъекция стола: линзы для спора в размышлении, наружу — решение. */
export function renderTable(roles: TableRole[], maxRoles = 4): string {
  const picked = roles.slice(0, maxRoles)
  const lines = [
    'Symbiont · стол проекта (задача выглядит high-stakes). Роли ниже — линзы для внутреннего спора в размышлении; наружу — решение и главные риски, не сам спор:',
  ]
  for (const r of picked) {
    lines.push(`- ${r.axis}: ${r.lens}. Проверить: ${r.checks.join('; ')}. Где искать: ${r.search}.`)
  }
  return lines.join('\n')
}
