/**
 * Роли стола: сгенерированные из профиля качества «люди проекта».
 *
 * Роль = линза + чек-лист + стратегия поиска, привязанные к оси профиля.
 * НЕ персона и не биография («ты — сеньор с 20-летним опытом» не добавляет
 * точности и повышает отказы — 3 независимых исследования в CONCEPT.md).
 * Хранятся нигде: роли — детерминированная проекция фактов профиля,
 * рендерятся по требованию и стоят ноль токенов пассивно.
 *
 * Симулированный стол (дефолт по CONCEPT §5): линзы инжектятся в контекст
 * high-stakes задачи, спор живёт в thinking одной сильной модели.
 */
import type { FactRow } from '../core/store'

export interface TableRole {
  axis: string
  lens: string
  checks: string[]
  search: string
}

