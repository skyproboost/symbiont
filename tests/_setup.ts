/**
 * Preload тест-процесса (bunfig.toml [test].preload): подметает СТАРЫЕ утёкшие
 * temp-каталоги прошлых прогонов, чтобы они не копились на C: (Windows/Defender
 * иногда не даёт rmrf снести sqlite-файлы сразу). Фильтр по возрасту (>30 мин) —
 * активные каталоги ТЕКУЩЕГО прогона не трогаем (они свежие). Fail-open.
 */
import { readdirSync, rmSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join } from 'node:path'

// bun test — ОДИН процесс, preload выполняется ПЕРВЫМ (до создания temp тестами),
// поэтому все существующие symbiont-* сейчас — утечки ПРОШЛЫХ прогонов: сносим все.
// Тем самым накопление ограничено одним прогоном (следующий подметёт этот).
try {
  const dir = tmpdir()
  for (const name of readdirSync(dir)) {
    if (!name.startsWith('symbiont-')) continue
    try {
      rmSync(join(dir, name), { recursive: true, force: true })
    } catch {
      /* занят/исчез — пропускаем */
    }
  }
} catch {
  /* нет доступа к temp — не мешаем тестам */
}

// Язык подачи в тестах фиксируется русским — исходным языком строк в коде.
// Иначе набор проверок зависел бы от локали машины: на англоязычной системе
// автоопределение выбрало бы английский, и половина проверок сравнивала бы
// русские ожидания с переведённым выводом. Определение языка проверяется
// отдельно (tests/i18n.test.ts), где env выставляется явно.
// ВАЖНО: пин действует только В ЭТОМ процессе. bun снапшотит окружение при
// старте, поэтому spawnSync без явного env отдаёт ребёнку ИСХОДНОЕ окружение —
// без этой строки. Тест, спавнящий языкочувствительный CLI, обязан передать
// env сам: { ...process.env, SYMBIONT_LANG: 'ru' } (поймано на macOS CI).
process.env.SYMBIONT_LANG = process.env.SYMBIONT_LANG ?? 'ru'
